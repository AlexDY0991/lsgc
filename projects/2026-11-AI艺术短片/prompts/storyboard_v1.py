def key(sid):
    return "sb_" + sid.replace(".", "_")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "table"
    if cmd == "table":
        for sid, t, seg, desc, prompt, reuse in SHOTS:
            print(f"{sid:5s} {t:9s} {seg:10s} {desc}  {'['+reuse+']' if reuse else ''}")
    elif cmd == "save":
        only = sys.argv[2:]
        for sid, t, seg, desc, prompt, reuse in SHOTS:
            if prompt is None or (only and sid not in only):
                continue
            subprocess.run(["python3", "tools/jm.py", S, "img", key(sid), "--ratio", "21:9",
                            "--title", f"分镜 {sid} {seg}", "--prompt", prompt], check=True)
